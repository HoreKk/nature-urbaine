import type { Access, CollectionConfig, CollectionSlug, Field } from 'payload';

/** Collections whose `relatedPictures` join orders a photo collection. */
export type GalleryOwnerSlug = 'reports' | 'interviews';

/** Server props of `PictureNav`, set by `pictureCollection`. */
export type PictureNavTarget = {
	collection: CollectionSlug;
	/** Relationship field on the photo that points at its owner. */
	ownerField: string;
	ownerCollection: GalleryOwnerSlug;
};

type PictureCollectionOptions = {
	slug: CollectionSlug;
	labels: CollectionConfig['labels'];
	owner: {
		field: string;
		collection: GalleryOwnerSlug;
		label: string;
	};
	/** Defaults to public: an owner with drafts must hide its unpublished photos. */
	read?: Access;
	/** Fields specific to this collection, placed after the owner. */
	fields?: Field[];
};

/**
 * One photo collection per gallery owner, never one table for several: Payload keys
 * an orderable join's hidden sort column by child slug + join name, so a shared
 * table could not carry a `relatedPictures` join from two owners (ADR-0004).
 */
export const pictureCollection = ({
	slug,
	labels,
	owner,
	read = () => true,
	fields = [],
}: PictureCollectionOptions): CollectionConfig => ({
	slug,
	labels,
	access: {
		read,
	},
	admin: {
		components: {
			edit: {
				beforeDocumentControls: [
					{
						path: '/payload/admin/PictureNav#PictureNav',
						serverProps: {
							collection: slug,
							ownerField: owner.field,
							ownerCollection: owner.collection,
						} satisfies PictureNavTarget,
					},
				],
			},
		},
	},
	upload: {
		mimeTypes: ['image/*'],
		adminThumbnail: 'thumbnail',
		displayPreview: true,
		// Variants (`thumbnail`, `medium`, `large`) are generated by
		// `sharpTransformer` in config.ts, from `image-variants.ts`.
	},
	fields: [
		{
			name: 'alt',
			type: 'text',
			required: true,
		},
		{
			name: owner.field,
			type: 'relationship',
			relationTo: owner.collection,
			label: owner.label,
			required: true,
		},
		...fields,
	],
	versions: false,
	authorship: false,
});
